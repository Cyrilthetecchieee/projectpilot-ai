"""Phase 3 Orchestrator Service for ProjectPilot AI.

Coordinates:
1. Normal autonomous specialist execution (Phase 1).
2. Controlled Reviewer feedback & self-correction loop (Phase 2).
3. Autonomous Issue Recovery & Replanning (Phase 3).

Phase 3 Features:
- Connects existing Report Issue workflow to the Orchestrator control layer.
- Deterministic recovery classification:
  * NO_ARTIFACT_CHANGE
  * PLAN_RECOVERY
  * ARCHITECTURE_RECOVERY
  * HUMAN_DECISION_REQUIRED
  * MANUAL_INTERVENTION_REQUIRED
- Targeted recovery (modifies only earliest affected upstream stage).
- Dependency-aware invalidation (Architecture changes invalidate Plan/Review/Tests; Plan changes invalidate Review/Tests).
- Human-in-the-loop decisions without hallucinating facts.
- Manual intervention handling for physical/hardware defects with user confirmation.
- Bounded recovery: max 2 recovery attempts per issue.
- Concurrency safety: mutual exclusion between normal autonomous pipeline and issue recovery.
- Targeted verification test scenarios generated by Test Agent.
"""

