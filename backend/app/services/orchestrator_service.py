    def _retrieve_and_apply_memory(
        self,
        project: ProjectContext,
        agent_name: str,
        run: OrchestratorRun,
        issue_context: dict[str, Any] | None = None,
    ) -> str | None:
        """Retrieves advisory engineering memories for the agent and logs to activity store."""
        if agent_name in ("Requirement Agent", "Requirements"):
            return None

        retrieved = self.memory_service.retrieve_relevant_memories(
            project,
            target_agent=agent_name,
            issue_context=issue_context,
            max_results=3,
            threshold=0.35,
        )
        if not retrieved:
            return None

        existing_ids = {rm.memory.memory_id for rm in run.retrieved_memories}
        for rm in retrieved:
            if rm.memory.memory_id not in existing_ids:
                run.retrieved_memories.append(rm)
                existing_ids.add(rm.memory.memory_id)

        for rm in retrieved:
            self.activity_store.setdefault(project.id, []).insert(0, {
                "agent": agent_name,
                "action": "Retrieved Engineering Memory",
                "provider": "System Memory",
                "model": "Deterministic Matcher",
                "status": "completed",
                "duration_ms": 2,
                "summary": f"Retrieved lesson {rm.memory.memory_id} (Relevance {int(rm.relevance_score * 100)}%): {rm.reason_retrieved}",
            })

        return self.memory_service.format_memory_for_prompt(retrieved)

    def _store_recovery_lesson(
        self,
        project: ProjectContext,
        target_issue: IssueRecord,
        classification: str,
        target: str,
        actions_taken: list[str],
        verification_summary: str,
    ) -> None:
        """Extracts and stores a reusable engineering lesson from a successful issue recovery."""
        cat_map = {
            "ARCHITECTURE_RECOVERY": "architecture",
            "PLAN_RECOVERY": "planning",
            "MANUAL_INTERVENTION_REQUIRED": "hardware",
            "NO_ARTIFACT_CHANGE": "operational",
            "HUMAN_DECISION_REQUIRED": "requirements",
        }
        category = cat_map.get(classification, "architecture")
        techs = []
        if project.tech_stack:
            techs.extend([t.strip() for t in project.tech_stack.split(",") if t.strip()])

        self.memory_service.store_lesson(
            category=category,
            problem_pattern=target_issue.analysis.issue_summary or target_issue.description,
            diagnosis="; ".join(target_issue.analysis.likely_causes) if target_issue.analysis.likely_causes else target_issue.description,
            successful_action="; ".join(actions_taken) if actions_taken else "; ".join(target_issue.analysis.recommended_fix),
            verification_summary=verification_summary,
            source_project_id=project.id,
            source_issue_id=target_issue.id,
            technologies=techs,
            affected_component_types=target_issue.analysis.affected_components or [],
            initial_confidence=0.85,
        )

    def _store_self_correction_lesson(
        self,
        project: ProjectContext,
        target_agent: str,
        corrected_risks: list[dict[str, Any]],
        summary: str,
    ) -> None:
        """Stores a lesson from successful Reviewer self-correction."""
        category = "architecture" if "Architecture" in target_agent else "planning"
        techs = []
        if project.tech_stack:
            techs.extend([t.strip() for t in project.tech_stack.split(",") if t.strip()])

        risk_titles = [r.get("title", "") for r in corrected_risks if r.get("title")]
        risk_details = [r.get("detail", "") for r in corrected_risks if r.get("detail")]

        self.memory_service.store_lesson(
            category=category,
            problem_pattern="; ".join(risk_titles) if risk_titles else "Reviewer blocking finding",
            diagnosis="; ".join(risk_details) if risk_details else "Identified potential engineering failure mode during review",
            successful_action=summary,
            verification_summary="Self-correction verified and passed subsequent Reviewer re-evaluation",
            source_project_id=project.id,
            technologies=techs,
            initial_confidence=0.85,
        )

    def get_or_create_run(self, project_id: str) -> OrchestratorRun:
        run = self.orchestrator_store.get(project_id)
        if not run:
            run = OrchestratorRun(project_id=project_id, state=OrchestratorState.IDLE)
            self.orchestrator_store[project_id] = run

        # Synchronize completed stages from current persistence
        completed = []
        if self.requirements_store.get(project_id):
            completed.append("Requirements")
        if self.architecture_store.get(project_id):
            completed.append("Architecture")
        if self.plan_store.get(project_id):
            completed.append("Execution Plan")
        if self.review_store.get(project_id):
            completed.append("Review")
        if self.test_store.get(project_id):
            completed.append("Testing")
        run.completed_stages = completed

        # If all 5 completed and not running and not in recovery, mark as COMPLETED
        if (
            len(completed) == 5
            and not run.is_running
            and run.state not in (OrchestratorState.PAUSED, OrchestratorState.FAILED)
            and run.recovery_state in ("IDLE", "RECOVERY_COMPLETED")
        ):
            run.state = OrchestratorState.COMPLETED
            if not run.completed_at:
                run.completed_at = self.now_iso()

        return run

    def start(self, project_id: str) -> OrchestratorRun:
        run = self.get_or_create_run(project_id)

        # Concurrency safety: cannot start normal run while issue recovery is actively running
        if run.active_issue_id and run.recovery_state in ("RECOVERING", "DIAGNOSING", "REVIEWING", "VERIFYING", "EVALUATING"):
            raise ValueError("Cannot start autonomous run while issue recovery is active")

        run.active_issue_id = ""
        run.recovery_state = "IDLE"
        run.recovery_type = ""
        run.recovery_target = ""
        run.recovery_attempt = 0
        run.manual_intervention_required = False
        run.manual_intervention_prompt = None

        run.state = OrchestratorState.RUNNING
        run.is_running = True
        run.failed_stage = ""
        run.last_error = ""
        run.error_message = ""
        run.human_input_required = False
        run.human_decision_prompt = None
        run.review_iteration = 1
        run.correction_count = 0
        run.max_corrections = 2
        run.correction_target = ""
        run.review_decision = ""
        run.unresolved_findings = []
        run.started_at = self.now_iso()
        run.completed_at = ""
        run.execution_count = 0
        self.save_db()
        return run

    def retry(self, project_id: str) -> OrchestratorRun:
        """Retry must rerun ONLY the failed stage, then proceed through remaining missing stages."""
        run = self.get_or_create_run(project_id)
        failed = run.failed_stage

        # Invalidate only the specific failed stage artifact if present
        if failed in ("Requirement Agent", "Requirements"):
            self.requirements_store.pop(project_id, None)
        elif failed in ("Architecture Agent", "Architecture"):
            self.architecture_store.pop(project_id, None)
        elif failed in ("Planner Agent", "Execution Plan"):
            self.plan_store.pop(project_id, None)
        elif failed in ("Reviewer Agent", "Review"):
            self.review_store.pop(project_id, None)
        elif failed in ("Test Agent", "Testing"):
            self.test_store.pop(project_id, None)

        run.state = OrchestratorState.RUNNING
        run.is_running = True
        run.failed_stage = ""
        run.last_error = ""
        run.error_message = ""
        run.human_input_required = False
        run.human_decision_prompt = None
        self.save_db()
        return run

    def stop(self, project_id: str) -> OrchestratorRun:
        run = self.get_or_create_run(project_id)
        run.is_running = False
        run.state = OrchestratorState.IDLE
        run.current_stage = ""
        run.current_agent = ""
        run.current_action = "Stopped by user"
        self.save_db()
        return run

    def provide_human_decision(self, project_id: str, decision: str) -> OrchestratorRun:
        run = self.get_or_create_run(project_id)
        project = self.projects.get(project_id)
        if not project:
            raise ValueError(f"Project '{project_id}' not found")

        decision_text = decision.strip()
        if project.constraints:
            project.constraints = f"{project.constraints}\n[User Specification]: {decision_text}"
        else:
            project.constraints = f"[User Specification]: {decision_text}"

        run.human_input_required = False
        run.human_decision_prompt = None
        run.human_decision_response = decision_text
        run.last_error = ""
        run.error_message = ""
        run.state = OrchestratorState.RUNNING
        run.is_running = True
        run.failed_stage = ""

        self.activity_store.setdefault(project_id, []).insert(0, {
            "agent": "Orchestrator",
            "action": "Human Decision Incorporated",
            "provider": "System Decision",
            "model": "Control Engine",
            "status": "completed",
            "duration_ms": 5,
            "summary": f"User provided decision: {decision_text}",
        })

        self.save_db()
        return run

    def continue_manually(self, project_id: str) -> OrchestratorRun:
        run = self.get_or_create_run(project_id)
        run.state = OrchestratorState.RUNNING
        run.is_running = True
        run.last_error = ""
        run.error_message = ""
        run.failed_stage = ""
        run.current_action = "Continuing manually to Testing"

        self.activity_store.setdefault(project_id, []).insert(0, {
            "agent": "Orchestrator",
            "action": "Continue Manually Authorized",
            "provider": "System Decision",
            "model": "Control Engine",
            "status": "completed",
            "duration_ms": 5,
            "summary": "User authorized manual continuation past review findings to Testing.",
        })

        self.save_db()
        return run

    def invalidate_downstream(self, project_id: str, trigger_stage: str, reason: str) -> list[str]:
        run = self.get_or_create_run(project_id)
        invalidated: list[str] = []

        if trigger_stage in ("Architecture Agent", "Architecture"):
            invalidated = ["Execution Plan", "Review", "Testing"]
            self.plan_store.pop(project_id, None)
            self.review_store.pop(project_id, None)
            self.test_store.pop(project_id, None)
        elif trigger_stage in ("Planner Agent", "Execution Plan"):
            invalidated = ["Review", "Testing"]
            self.review_store.pop(project_id, None)
            self.test_store.pop(project_id, None)

        for stage in invalidated:
            if stage in run.completed_stages:
                run.completed_stages.remove(stage)

        if invalidated:
            rec = InvalidationRecord(
                timestamp=self.now_iso(),
                trigger_stage=trigger_stage,
                invalidated_stages=invalidated,
                reason=reason,
            )
            run.invalidation_history.append(rec)
            self.activity_store.setdefault(project_id, []).insert(0, {
                "agent": "Orchestrator",
                "action": "Invalidate Downstream Stages",
                "provider": "System Decision",
                "model": "Control Engine",
                "status": "completed",
                "duration_ms": 5,
                "summary": f"{trigger_stage} changed: invalidated {', '.join(invalidated)}. Reason: {reason}",
            })
            self.save_db()

        return invalidated

    def evaluate_review(
        self,
        project: ProjectContext,
        review: ReviewResponse,
        architecture: ArchitectureResponse | None,
        plan: PlannerResponse | None,
    ) -> tuple[str, str, list[dict[str, Any]], dict[str, Any] | None]:
        """Classify review findings deterministically into PASS, HUMAN_DECISION_REQUIRED, or CORRECTION_REQUIRED."""
        blocking_risks: list[dict[str, Any]] = []

        human_keywords = [
            "unspecified",
            "not specified",
            "missing specification",
            "requires user choice",
            "user decision",
            "human decision",
            "conflicting requirement",
            "contradictory requirement",
            "material selection required",
            "safety threshold unspecified",
            "clarification needed",
            "external approval required",
            "missing project information",
            "cannot be determined without user",
            "undefined parameter",
            "acceptance threshold is ambiguous",
        ]

        for r in review.risks:
            sev = str(r.severity).lower()
            text = f"{r.title} {r.detail} {r.recommendation}".lower()
            if sev in ("critical", "high"):
                # 1. Check for missing project information or required user choices
                if any(kw in text for kw in human_keywords):
                    question = r.recommendation or f"Please clarify: {r.title}"
                    if "unspecified" in text or "not specified" in text:
                        question = f"Clarify specification for '{r.title}': What threshold or parameter should be satisfied?"

                    prompt_data = {
                        "question": question,
                        "affected_stage": "Requirements",
                        "evidence": f"{r.title}: {r.detail}",
                        "mitigation": r.recommendation,
                    }
                    return "HUMAN_DECISION_REQUIRED", "Requirements", [r.model_dump()], prompt_data

                # 2. Check if actionable engineering blocker
                if sev == "critical":
                    blocking_risks.append(r.model_dump())
                elif sev == "high":
                    blocker_indicators = [
                        "blocker", "blocks implementation", "cannot proceed", "fatal", "prevents testing",
                        "no recovery", "offline recovery", "data loss", "unhandled failure", "missing component",
                        "deadlock", "shoot-through", "runaway", "unspecified", "contradiction",
                        "omission", "buffer overrun", "overflow", "missing dependency", "missing prerequisite",
                    ]
                    if any(kw in text for kw in blocker_indicators):
                        blocking_risks.append(r.model_dump())

        # If no blocking critical or high severity risks, it's a clean PASS
        if not blocking_risks:
            return "PASS", "", [], None

        # Determine earliest affected stage
        arch_comp_names = [c.name.lower() for c in (architecture.components if architecture else [])]
        arch_comp_ids = [c.id.lower() for c in (architecture.components if architecture else [])]

        arch_keywords = [
            "component", "subsystem", "hardware", "firmware", "schematic",
            "sensor", "actuator", "microcontroller", "pin", "protocol",
            "interface", "bus", "circuit", "topology", "payload",
            "connection", "spi", "i2c", "uart", "can-bus", "wifi", "wi-fi",
            "bluetooth", "ble", "mqtt", "recovery policy", "failover", "buffer overrun",
            "power supply", "adc", "dma", "dsp", "telemetry", "offline recovery",
        ]

        affects_architecture = False
        affects_planning = False

        for risk in blocking_risks:
            text = f"{risk.get('title', '')} {risk.get('detail', '')} {risk.get('recommendation', '')}".lower()
            for name in arch_comp_names:
                if name in text:
                    affects_architecture = True
                    break
            for cid in arch_comp_ids:
                if cid in text:
                    affects_architecture = True
                    break
            if any(kw in text for kw in arch_keywords):
                affects_architecture = True

            plan_keywords = ["task", "milestone", "schedule", "effort", "dependency", "timeline", "critical path"]
            if any(kw in text for kw in plan_keywords):
                affects_planning = True

        if affects_architecture:
            target = "Architecture Agent"
        elif affects_planning:
            target = "Planner Agent"
        else:
            target = "Architecture Agent"

        return "CORRECTION_REQUIRED", target, blocking_risks, None

