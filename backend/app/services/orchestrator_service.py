    def classify_recovery(
        self,
        project: ProjectContext,
        analysis: IssueAnalysisResponse | dict,
        description: str = "",
    ) -> tuple[str, str, dict[str, Any]]:
        """Deterministically classifies an issue diagnosis into one of the 5 recovery types."""
        if isinstance(analysis, dict):
            analysis = IssueAnalysisResponse(**analysis)

        combined_text = (
            f"{analysis.issue_summary} "
            f"{' '.join(analysis.likely_causes)} "
            f"{' '.join(analysis.recommended_fix)} "
            f"{analysis.recommended_next_action} "
            f"{description}"
        ).lower()

        # 1. Check MANUAL_INTERVENTION_REQUIRED (Physical/Hardware defects)
        physical_keywords = [
            "physically damaged", "physical damage", "broken pcb", "damaged sensor", "burnt", "fried",
            "soldering", "hardware defect", "cable disconnected", "loose wire", "mechanical repair",
            "physical inspection", "component replacement", "replace sensor", "hardware repair",
            "replace hardware", "damaged hardware", "short circuit", "defective unit", "hardware failure"
        ]
        if any(kw in combined_text for kw in physical_keywords):
            prompt_data = {
                "likely_cause": analysis.likely_causes[0] if analysis.likely_causes else "Physical hardware defect detected",
                "recommended_action": analysis.recommended_fix[0] if analysis.recommended_fix else "Inspect and repair/replace physical hardware component.",
                "affected_components": analysis.affected_components or ["Hardware Sensor/PCB"],
                "verification_required": f"Verify component connectivity and sensor integrity after physical intervention for: {analysis.issue_summary}",
            }
            return "MANUAL_INTERVENTION_REQUIRED", "Hardware/Physical", prompt_data

        # 2. Check HUMAN_DECISION_REQUIRED (Unknown engineering parameters or missing user decisions)
        human_keywords = [
            "unspecified", "not specified", "missing specification", "requires user choice", "user decision",
            "human decision", "choose replacement", "cost increase", "safety threshold unspecified",
            "approve scope change", "alternative selection required", "user approval required", "tradeoff required"
        ]
        if any(kw in combined_text for kw in human_keywords):
            prompt_data = {
                "question": analysis.recommended_next_action or f"Clarify specification or decision for: {analysis.issue_summary}",
                "affected_stage": "Requirements",
                "evidence": f"Likely cause: {analysis.likely_causes[0] if analysis.likely_causes else ''}. Fix options: {', '.join(analysis.recommended_fix)}",
                "mitigation": ", ".join(analysis.recommended_fix),
            }
            return "HUMAN_DECISION_REQUIRED", "Requirements", prompt_data

        # 3. Check ARCHITECTURE_RECOVERY (Design-level flaw)
        arch_keywords = [
            "offline buffer", "storage", "buffer overrun", "ring buffer", "interface conflict",
            "communication boundary", "fail-safe", "redundancy", "architecture", "hardware design",
            "pinout", "protocol mismatch", "telemetry loss", "missing subsystem", "galvanic isolation",
            "circuit", "power rail", "isolation barrier"
        ]
        has_arch_component = bool(analysis.affected_components and len(analysis.affected_components) > 0)
        if any(kw in combined_text for kw in arch_keywords) or (has_arch_component and analysis.severity in ("critical", "high")):
            issue_dict = {
                "description": description or analysis.issue_summary,
                "likely_causes": analysis.likely_causes,
                "recommended_fix": analysis.recommended_fix,
                "affected_components": analysis.affected_components,
                "severity": str(analysis.severity),
            }
            return "ARCHITECTURE_RECOVERY", "Architecture Agent", issue_dict

        # 4. Check PLAN_RECOVERY (Planning / Task dependencies / Sequencing)
        plan_keywords = [
            "missing task", "dependency", "missing prerequisite", "sequencing", "schedule",
            "milestone", "prerequisite", "deadlock", "work breakdown", "task order", "timing"
        ]
        if analysis.recovery_task.needed or len(analysis.blocked_tasks) > 0 or any(kw in combined_text for kw in plan_keywords):
            issue_dict = {
                "description": description or analysis.issue_summary,
                "likely_causes": analysis.likely_causes,
                "recommended_fix": analysis.recommended_fix,
                "blocked_tasks": analysis.blocked_tasks,
                "recovery_task": analysis.recovery_task.model_dump(),
                "severity": str(analysis.severity),
            }
            return "PLAN_RECOVERY", "Planner Agent", issue_dict

        # 5. NO_ARTIFACT_CHANGE (Transient operational issue)
        issue_dict = {
            "description": description or analysis.issue_summary,
            "likely_causes": analysis.likely_causes,
            "recommended_fix": analysis.recommended_fix,
            "severity": str(analysis.severity),
        }
        return "NO_ARTIFACT_CHANGE", "Operational/Testing", issue_dict

    def start_issue_recovery(self, project_id: str, issue_id: str) -> OrchestratorRun:
        run = self.get_or_create_run(project_id)

        # Concurrency safety: check if normal autonomous run is in progress
        if run.is_running and run.state == OrchestratorState.RUNNING and not run.active_issue_id:
            raise ValueError("Cannot start issue recovery while normal autonomous pipeline is running")

        run.active_issue_id = issue_id
        run.recovery_state = "DIAGNOSING"
        run.recovery_attempt = 0
        run.max_recovery_attempts = 2
        run.state = OrchestratorState.RUNNING
        run.is_running = True
        run.failed_stage = ""
        run.last_error = ""
        run.error_message = ""
        run.manual_intervention_required = False
        run.manual_intervention_prompt = None

        self.save_db()
        return run

    def confirm_manual_intervention(self, project_id: str) -> OrchestratorRun:
        run = self.get_or_create_run(project_id)
        run.manual_intervention_required = False
        run.manual_intervention_prompt = None
        run.manual_intervention_completed = True
        run.recovery_state = "VERIFYING"
        run.state = OrchestratorState.RUNNING
        run.is_running = True
        run.last_error = ""
        run.error_message = ""

        self.activity_store.setdefault(project_id, []).insert(0, {
            "agent": "Orchestrator",
            "action": "Manual Intervention Confirmed",
            "provider": "System Decision",
            "model": "Control Engine",
            "status": "completed",
            "duration_ms": 5,
            "summary": "User confirmed manual intervention completed. Proceeding to verification.",
        })

        self.save_db()
        return run

    def retry_recovery(self, project_id: str) -> OrchestratorRun:
        run = self.get_or_create_run(project_id)
        run.state = OrchestratorState.RUNNING
        run.is_running = True
        run.last_error = ""
        run.error_message = ""
        # Preserve failed_stage so recovery retries ONLY the failed stage
        run.recovery_state = "RECOVERING"
        self.save_db()
        return run

    def stop_recovery(self, project_id: str) -> OrchestratorRun:
        run = self.get_or_create_run(project_id)
        run.active_issue_id = ""
        run.recovery_state = "IDLE"
        run.is_running = False
        run.state = OrchestratorState.IDLE
        run.current_action = "Issue recovery stopped by user"
        self.save_db()
        return run

    async def run_issue_recovery_pipeline(self, project_id: str, issue_id: str) -> None:
        """Main Phase 3 issue recovery loop."""
        run = self.get_or_create_run(project_id)
        project = self.projects.get(project_id)
        if not project:
            run.state = OrchestratorState.FAILED
            run.is_running = False
            run.last_error = "Project context missing"
            self.save_db()
            return

        # Find target issue
        project_issues = self.issues_store.get(project_id, [])
        target_issue = next((iss for iss in project_issues if iss.id == issue_id), None)
        if not target_issue:
            run.state = OrchestratorState.FAILED
            run.is_running = False
            run.last_error = f"Issue '{issue_id}' not found"
            self.save_db()
            return

        run.recovery_state = "EVALUATING"
        run.active_issue_id = issue_id
        run.is_running = True
        run.state = OrchestratorState.RUNNING
        classification, target, prompt_data = self.classify_recovery(
            project, target_issue.analysis, target_issue.description
        )
        run.recovery_type = classification
        run.recovery_target = target

        self.activity_store.setdefault(project_id, []).insert(0, {
            "agent": "Orchestrator",
            "action": f"Classified Issue Recovery: {classification}",
            "provider": "System Decision",
            "model": "Control Engine",
            "status": "completed",
            "duration_ms": 5,
            "summary": f"Target: {target}. Issue: {target_issue.analysis.issue_summary}",
        })
        self.save_db()

        # ---------------------------------------------------------------------
        # BRANCH 1: MANUAL_INTERVENTION_REQUIRED
        # ---------------------------------------------------------------------
        if classification == "MANUAL_INTERVENTION_REQUIRED":
            if not getattr(run, "manual_intervention_completed", False):
                run.recovery_state = "AWAITING_MANUAL_INTERVENTION"
                run.manual_intervention_required = True
                run.manual_intervention_prompt = ManualInterventionPrompt(issue_id=issue_id, **prompt_data)
                run.state = OrchestratorState.PAUSED
                run.is_running = False
                run.last_error = f"Manual intervention required: {prompt_data.get('recommended_action')}"
                run.error_message = run.last_error
                self.save_db()
                return
            else:
                # Manual intervention confirmed: generate targeted verification
                run.recovery_state = "VERIFYING"
                run.current_action = "Generating post-intervention verification"
                self.save_db()

                reqs = self.requirements_store.get(project_id)
                arch = self.architecture_store.get(project_id)
                plan = self.plan_store.get(project_id)
                review = self.review_store.get(project_id)
                if reqs and arch:
                    try:
                        mem_ctx = self._retrieve_and_apply_memory(project, "Test Agent", run, issue_context=prompt_data)
                        test_analysis, test_duration = self.test_agent.analyze(
                            project, reqs, arch, plan=plan, review=review, issue_context=prompt_data, memory_context=mem_ctx
                        )
                        test_resp = TestResponse(
                            **test_analysis.model_dump(),
                            project_id=project_id,
                            provider="Nebius Token Factory",
                            model=self.test_agent.model,
                            duration_ms=test_duration,
                        )
                        self.test_store[project_id] = test_resp
                    except Exception as e:
                        logger.warning(f"Targeted post-intervention test verification failed: {e}")

                run.recovery_state = "RECOVERY_COMPLETED"
                run.state = OrchestratorState.COMPLETED
                run.is_running = False
                run.current_action = "RECOVERY COMPLETE - READY FOR VERIFICATION"
                target_issue.status = "Ready for Verification"

                rec = RecoveryRecord(
                    id=f"rec-{uuid.uuid4().hex[:6]}",
                    issue_id=issue_id,
                    timestamp=self.now_iso(),
                    classification=classification,
                    target=target,
                    summary=f"Manual intervention verified for: {target_issue.analysis.issue_summary}",
                    actions_taken=[
                        f"Manual intervention confirmed: {prompt_data.get('recommended_action')}",
                        "Post-intervention verification strategy generated",
                    ],
                    result="Success",
                )
                run.recovery_history.append(rec)
                try:
                    self._store_recovery_lesson(
                        project,
                        target_issue,
                        classification,
                        target,
                        rec.actions_taken,
                        "Post-intervention verification strategy generated",
                    )
                except Exception as e:
                    logger.warning(f"Failed to store recovery lesson: {e}")
                self.save_db()
                return

        # ---------------------------------------------------------------------
        # BRANCH 2: HUMAN_DECISION_REQUIRED
        # ---------------------------------------------------------------------
        if classification == "HUMAN_DECISION_REQUIRED":
            if not getattr(run, "human_decision_response", None):
                run.recovery_state = "AWAITING_HUMAN_DECISION"
                run.human_input_required = True
                run.human_decision_prompt = HumanDecisionPrompt(**prompt_data)
                run.state = OrchestratorState.PAUSED
                run.is_running = False
                run.last_error = f"Human decision required: {prompt_data.get('question')}"
                run.error_message = run.last_error
                self.save_db()
                return
            else:
                prompt_data["human_decision"] = getattr(run, "human_decision_response", "")

        # ---------------------------------------------------------------------
        # BRANCH 3: NO_ARTIFACT_CHANGE (Operational / Transient)
        # ---------------------------------------------------------------------
        if classification == "NO_ARTIFACT_CHANGE":
            run.recovery_state = "VERIFYING"
            run.current_action = "Generating operational verification"
            self.save_db()

            reqs = self.requirements_store.get(project_id)
            arch = self.architecture_store.get(project_id)
            plan = self.plan_store.get(project_id)
            review = self.review_store.get(project_id)

            if reqs and arch:
                try:
                    mem_ctx = self._retrieve_and_apply_memory(project, "Test Agent", run, issue_context=prompt_data)
                    test_analysis, test_duration = self.test_agent.analyze(
                        project, reqs, arch, plan=plan, review=review, issue_context=prompt_data, memory_context=mem_ctx
                    )
                    test_resp = TestResponse(
                        **test_analysis.model_dump(),
                        project_id=project_id,
                        provider="Nebius Token Factory",
                        model=self.test_agent.model,
                        duration_ms=test_duration,
                    )
                    self.test_store[project_id] = test_resp
                except Exception as e:
                    logger.warning(f"Targeted test verification failed: {e}")

            run.recovery_state = "RECOVERY_COMPLETED"
            run.state = OrchestratorState.COMPLETED
            run.is_running = False
            run.current_action = "RECOVERY COMPLETE - READY FOR VERIFICATION"
            target_issue.status = "Ready for Verification"

            rec = RecoveryRecord(
                id=f"rec-{uuid.uuid4().hex[:6]}",
                issue_id=issue_id,
                timestamp=self.now_iso(),
                classification=classification,
                target=target,
                summary=f"Operational resolution confirmed for: {target_issue.analysis.issue_summary}",
                actions_taken=["Operational recovery recorded", "Targeted verification strategy confirmed"],
                result="Success",
            )
            run.recovery_history.append(rec)
            try:
                self._store_recovery_lesson(
                    project,
                    target_issue,
                    classification,
                    target,
                    rec.actions_taken,
                    "Targeted verification strategy confirmed",
                )
            except Exception as e:
                logger.warning(f"Failed to store recovery lesson: {e}")
            self.save_db()
            return

        # ---------------------------------------------------------------------
        # BRANCH 4: ARCHITECTURE_RECOVERY & PLAN_RECOVERY (Bounded Loop <= 2)
        # ---------------------------------------------------------------------
        while run.recovery_attempt < run.max_recovery_attempts and run.is_running:
            if not run.failed_stage:
                run.recovery_attempt += 1
            run.recovery_state = "RECOVERING"
            self.save_db()

            reqs = self.requirements_store.get(project_id)
            if not reqs:
                self._handle_failure(run, project_id, "Requirement Agent", "Requirements", RuntimeError("Requirements missing"))
                return

            arch_resp = self.architecture_store.get(project_id)
            plan_resp = self.plan_store.get(project_id)

            if classification == "ARCHITECTURE_RECOVERY":
                arch_resp = self.architecture_store.get(project_id)
                # Check if architecture was already recovered and failure occurred at Planner
                arch_already_recovered = (
                    arch_resp is not None
                    and "Architecture" in run.completed_stages
                    and run.failed_stage in ("Planner Agent", "Execution Plan")
                )

                if not arch_already_recovered:
                    self.invalidate_downstream(project_id, "Architecture Agent", f"Issue recovery: {target_issue.analysis.issue_summary}")
                    existing_arch = self.architecture_store.get(project_id)

                    run.current_stage = "Architecture"
                    run.current_agent = "Architecture Agent"
                    run.current_action = f"Recovering Architecture (Attempt {run.recovery_attempt})"
                    self.save_db()

                    try:
                        mem_ctx = self._retrieve_and_apply_memory(project, "Architecture Agent", run, issue_context=prompt_data)
                        corr_arch, dur_arch = self.architecture_agent.analyze(
                            project, reqs, existing_architecture=existing_arch, issue_context=prompt_data, memory_context=mem_ctx
                        )
                        arch_resp = ArchitectureResponse(
                            **corr_arch.model_dump(),
                            project_id=project_id,
                            provider="Nebius Token Factory",
                            model=self.architecture_agent.model,
                            duration_ms=dur_arch,
                        )
                        self.architecture_store[project_id] = arch_resp
                        self.activity_store.setdefault(project_id, []).insert(0, {
                            "agent": "Architecture Agent",
                            "action": f"Recover Architecture (Attempt {run.recovery_attempt})",
                            "provider": "Nebius Token Factory",
                            "model": self.architecture_agent.model,
                            "status": "completed",
                            "duration_ms": dur_arch,
                            "summary": f"Revised architecture for issue: {corr_arch.summary}",
                        })
                        if "Architecture" not in run.completed_stages:
                            run.completed_stages.append("Architecture")
                        run.execution_count += 1
                        self.save_db()
                    except Exception as e:
                        self._handle_failure(run, project_id, "Architecture Agent", "Architecture Recovery", e)
                        return
                else:
                    logger.info("Preserving already recovered Architecture; retrying only Planner Agent")

                # Regenerate Plan downstream
                run.failed_stage = ""
                run.current_stage = "Execution Plan"
                run.current_agent = "Planner Agent"
                run.current_action = "Regenerating Execution Plan"
                self.save_db()

                existing_plan = self.plan_store.get(project_id)
                try:
                    mem_ctx = self._retrieve_and_apply_memory(project, "Planner Agent", run, issue_context=prompt_data)
                    plan_analysis, plan_dur = self.planner_agent.analyze(
                        project, reqs, arch_resp, existing_plan=existing_plan, issue_context=prompt_data, memory_context=mem_ctx
                    )
                    plan_resp = PlannerResponse(
                        **plan_analysis.model_dump(),
                        project_id=project_id,
                        provider="Nebius Token Factory",
                        model=self.planner_agent.model,
                        duration_ms=plan_dur,
                    )
                    self.plan_store[project_id] = plan_resp
                    self.activity_store.setdefault(project_id, []).insert(0, {
                        "agent": "Planner Agent",
                        "action": "Regenerate Plan for Issue Recovery",
                        "provider": "Nebius Token Factory",
                        "model": self.planner_agent.model,
                        "status": "completed",
                        "duration_ms": plan_dur,
                        "summary": f"Plan updated with recovery tasks: {plan_analysis.summary}",
                    })
                    if "Execution Plan" not in run.completed_stages:
                        run.completed_stages.append("Execution Plan")
                    run.execution_count += 1
                    self.save_db()
                except Exception as e:
                    self._handle_failure(run, project_id, "Planner Agent", "Plan Regeneration", e)
                    return

            elif classification in ("PLAN_RECOVERY", "HUMAN_DECISION_REQUIRED"):
                self.invalidate_downstream(project_id, "Planner Agent", f"Issue recovery: {target_issue.analysis.issue_summary}")
                existing_plan = self.plan_store.get(project_id)
                arch_resp = self.architecture_store.get(project_id)
                if not arch_resp:
                    self._handle_failure(run, project_id, "Planner Agent", "Plan Recovery", RuntimeError("Architecture missing"))
                    return

                run.current_stage = "Execution Plan"
                run.current_agent = "Planner Agent"
                run.current_action = f"Recovering Execution Plan (Attempt {run.recovery_attempt})"
                self.save_db()

                try:
                    mem_ctx = self._retrieve_and_apply_memory(project, "Planner Agent", run, issue_context=prompt_data)
                    plan_analysis, plan_dur = self.planner_agent.analyze(
                        project, reqs, arch_resp, existing_plan=existing_plan, issue_context=prompt_data, memory_context=mem_ctx
                    )
                    plan_resp = PlannerResponse(
                        **plan_analysis.model_dump(),
                        project_id=project_id,
                        provider="Nebius Token Factory",
                        model=self.planner_agent.model,
                        duration_ms=plan_dur,
                    )
                    self.plan_store[project_id] = plan_resp
                    self.activity_store.setdefault(project_id, []).insert(0, {
                        "agent": "Planner Agent",
                        "action": f"Recover Execution Plan (Attempt {run.recovery_attempt})",
                        "provider": "Nebius Token Factory",
                        "model": self.planner_agent.model,
                        "status": "completed",
                        "duration_ms": plan_dur,
                        "summary": f"Plan updated with recovery tasks: {plan_analysis.summary}",
                    })
                    if "Execution Plan" not in run.completed_stages:
                        run.completed_stages.append("Execution Plan")
                    run.execution_count += 1
                    self.save_db()
                except Exception as e:
                    self._handle_failure(run, project_id, "Planner Agent", "Plan Recovery", e)
                    return

            # Re-review system
            run.recovery_state = "REVIEWING"
            run.current_stage = "Review"
            run.current_agent = "Reviewer Agent"
            run.current_action = "Re-reviewing System Post-Recovery"
            self.save_db()

            try:
                mem_ctx = self._retrieve_and_apply_memory(project, "Reviewer Agent", run, issue_context=prompt_data)
                rev_analysis, rev_dur = self.reviewer_agent.analyze(project, reqs, arch_resp, plan=plan_resp, memory_context=mem_ctx)
                rev_resp = ReviewResponse(
                    **rev_analysis.model_dump(),
                    project_id=project_id,
                    provider="Nebius Token Factory",
                    model=self.reviewer_agent.model,
                    duration_ms=rev_dur,
                )
                self.review_store[project_id] = rev_resp
                self.activity_store.setdefault(project_id, []).insert(0, {
                    "agent": "Reviewer Agent",
                    "action": "Re-review System Post-Recovery",
                    "provider": "Nebius Token Factory",
                    "model": self.reviewer_agent.model,
                    "status": "completed",
                    "duration_ms": rev_dur,
                    "summary": f"Re-review complete: {len(rev_analysis.risks)} risks assessed",
                })
                if "Review" not in run.completed_stages:
                    run.completed_stages.append("Review")
                run.execution_count += 1
                self.save_db()
            except Exception as e:
                self._handle_failure(run, project_id, "Reviewer Agent", "Re-review Post-Recovery", e)
                return

            # Evaluate review
            decision, _, blocking, _ = self.evaluate_review(project, rev_resp, arch_resp, plan_resp)
            if decision == "PASS":
                # Generate targeted verification strategy
                run.recovery_state = "VERIFYING"
                run.current_stage = "Testing"
                run.current_agent = "Test Agent"
                run.current_action = "Generating Targeted Issue Verification"
                self.save_db()

                try:
                    mem_ctx = self._retrieve_and_apply_memory(project, "Test Agent", run, issue_context=prompt_data)
                    test_analysis, test_dur = self.test_agent.analyze(
                        project, reqs, arch_resp, plan=plan_resp, review=rev_analysis, issue_context=prompt_data, memory_context=mem_ctx
                    )
                    test_resp = TestResponse(
                        **test_analysis.model_dump(),
                        project_id=project_id,
                        provider="Nebius Token Factory",
                        model=self.test_agent.model,
                        duration_ms=test_dur,
                    )
                    self.test_store[project_id] = test_resp
                    self.activity_store.setdefault(project_id, []).insert(0, {
                        "agent": "Test Agent",
                        "action": "Generate Targeted Verification Strategy",
                        "provider": "Nebius Token Factory",
                        "model": self.test_agent.model,
                        "status": "completed",
                        "duration_ms": test_dur,
                        "summary": f"{len(test_analysis.test_cases)} targeted verification scenarios generated",
                    })
                    if "Testing" not in run.completed_stages:
                        run.completed_stages.append("Testing")
                    run.execution_count += 1
                except Exception as e:
                    self._handle_failure(run, project_id, "Test Agent", "Verification Generation", e)
                    return

                run.recovery_state = "RECOVERY_COMPLETED"
                run.state = OrchestratorState.COMPLETED
                run.is_running = False
                run.current_action = "RECOVERY COMPLETE - READY FOR VERIFICATION"
                target_issue.status = "Ready for Verification"

                rec = RecoveryRecord(
                    id=f"rec-{uuid.uuid4().hex[:6]}",
                    issue_id=issue_id,
                    timestamp=self.now_iso(),
                    classification=classification,
                    target=target,
                    summary=f"Resolved issue: {target_issue.analysis.issue_summary}",
                    actions_taken=[
                        f"{target} revised",
                        "Plan updated",
                        "Re-review passed",
                        "Targeted verification strategy generated",
                    ],
                    result="Success",
                )
                run.recovery_history.append(rec)
                try:
                    self._store_recovery_lesson(
                        project,
                        target_issue,
                        classification,
                        target,
                        rec.actions_taken,
                        f"Verified by Test Agent: {len(test_analysis.test_cases)} scenarios",
                    )
                except Exception as e:
                    logger.warning(f"Failed to store recovery lesson: {e}")
                self.save_db()
                return

            else:
                # If still unresolved and reached maximum limit, pause
                if run.recovery_attempt >= run.max_recovery_attempts:
                    run.recovery_state = "RECOVERY_FAILED"
                    run.state = OrchestratorState.PAUSED
                    run.is_running = False
                    run.last_error = f"Issue remains unresolved after {run.max_recovery_attempts} autonomous recovery attempts."
                    run.error_message = run.last_error
                    run.unresolved_findings = blocking
                    self.save_db()
                    return

