    # PHASE 1 & 2 PIPELINE
    # =========================================================================

    async def run_pipeline(self, project_id: str) -> None:
        """Main autonomous execution and self-correction loop."""
        run = self.get_or_create_run(project_id)
        project = self.projects.get(project_id)
        if not project:
            run.state = OrchestratorState.FAILED
            run.is_running = False
            run.last_error = "Project context missing"
            run.error_message = "Project context missing"
            self.save_db()
            return

        max_total_specialist_executions = 15

        while run.is_running and run.state == OrchestratorState.RUNNING:
            if run.execution_count >= max_total_specialist_executions:
                run.state = OrchestratorState.PAUSED
                run.is_running = False
                run.last_error = f"Safety execution limit ({max_total_specialist_executions}) reached."
                run.error_message = run.last_error
                self.save_db()
                break

            # 1. REQUIREMENTS STAGE
            if not self.requirements_store.get(project_id):
                run.current_stage = "Requirements"
                run.current_agent = "Requirement Agent"
                run.current_action = "Running Requirement Agent"
                self.save_db()

                self.activity_store.setdefault(project_id, []).insert(0, {
                    "agent": "Orchestrator",
                    "action": "Selected Requirement Agent",
                    "provider": "System Decision",
                    "model": "Control Engine",
                    "status": "completed",
                    "duration_ms": 5,
                    "summary": "Autonomous progression to Requirements",
                })

                try:
                    analysis, duration_ms = requirement_agent.analyze(project)
                    resp = RequirementsResponse(
                        **analysis.model_dump(),
                        project_id=project_id,
                        provider="Nebius Token Factory",
                        model=requirement_agent.model,
                        duration_ms=duration_ms,
                        summary=f"{len(analysis.functional_requirements)} functional and {len(analysis.non_functional_requirements)} non-functional requirements identified",
                    )
                    self.requirements_store[project_id] = resp
                    self.activity_store.setdefault(project_id, []).insert(0, {
                        "agent": "Requirement Agent",
                        "action": "Analyze Requirements",
                        "provider": "Nebius Token Factory",
                        "model": requirement_agent.model,
                        "status": "completed",
                        "duration_ms": duration_ms,
                        "summary": resp.summary,
                    })
                    if "Requirements" not in run.completed_stages:
                        run.completed_stages.append("Requirements")
                    run.execution_count += 1
                    self.save_db()
                    await asyncio.sleep(0.5)
                    continue
                except Exception as e:
                    self._handle_failure(run, project_id, "Requirement Agent", "Requirements", e)
                    return

            # 2. ARCHITECTURE STAGE
            if not self.architecture_store.get(project_id):
                reqs = self.requirements_store.get(project_id)
                if not reqs:
                    self._handle_failure(run, project_id, "Architecture Agent", "Architecture", RuntimeError("Requirements missing"))
                    return

                run.current_stage = "Architecture"
                run.current_agent = "Architecture Agent"
                run.current_action = "Running Architecture Agent"
                self.save_db()

                self.activity_store.setdefault(project_id, []).insert(0, {
                    "agent": "Orchestrator",
                    "action": "Selected Architecture Agent",
                    "provider": "System Decision",
                    "model": "Control Engine",
                    "status": "completed",
                    "duration_ms": 5,
                    "summary": "Autonomous progression to Architecture",
                })

                try:
                    mem_ctx = self._retrieve_and_apply_memory(project, "Architecture Agent", run)
                    analysis, duration_ms = self.architecture_agent.analyze(project, reqs, memory_context=mem_ctx)
                    resp = ArchitectureResponse(
                        **analysis.model_dump(),
                        project_id=project_id,
                        provider="Nebius Token Factory",
                        model=self.architecture_agent.model,
                        duration_ms=duration_ms,
                    )
                    self.architecture_store[project_id] = resp
                    self.activity_store.setdefault(project_id, []).insert(0, {
                        "agent": "Architecture Agent",
                        "action": "Generate Architecture",
                        "provider": "Nebius Token Factory",
                        "model": self.architecture_agent.model,
                        "status": "completed",
                        "duration_ms": duration_ms,
                        "summary": analysis.summary,
                    })
                    if "Architecture" not in run.completed_stages:
                        run.completed_stages.append("Architecture")
                    run.execution_count += 1
                    self.save_db()
                    await asyncio.sleep(0.5)
                    continue
                except Exception as e:
                    self._handle_failure(run, project_id, "Architecture Agent", "Architecture", e)
                    return

            # 3. PLANNER STAGE
            if not self.plan_store.get(project_id):
                reqs = self.requirements_store.get(project_id)
                arch = self.architecture_store.get(project_id)
                if not reqs or not arch:
                    self._handle_failure(run, project_id, "Planner Agent", "Execution Plan", RuntimeError("Requirements or Architecture missing"))
                    return

                run.current_stage = "Execution Plan"
                run.current_agent = "Planner Agent"
                run.current_action = "Running Planner Agent"
                self.save_db()

                self.activity_store.setdefault(project_id, []).insert(0, {
                    "agent": "Orchestrator",
                    "action": "Selected Planner Agent",
                    "provider": "System Decision",
                    "model": "Control Engine",
                    "status": "completed",
                    "duration_ms": 5,
                    "summary": "Autonomous progression to Execution Plan",
                })

                try:
                    mem_ctx = self._retrieve_and_apply_memory(project, "Planner Agent", run)
                    analysis, duration_ms = self.planner_agent.analyze(project, reqs, arch, memory_context=mem_ctx)
                    resp = PlannerResponse(
                        **analysis.model_dump(),
                        project_id=project_id,
                        provider="Nebius Token Factory",
                        model=self.planner_agent.model,
                        duration_ms=duration_ms,
                    )
                    self.plan_store[project_id] = resp
                    self.activity_store.setdefault(project_id, []).insert(0, {
                        "agent": "Planner Agent",
                        "action": "Generate Execution Plan",
                        "provider": "Nebius Token Factory",
                        "model": self.planner_agent.model,
                        "status": "completed",
                        "duration_ms": duration_ms,
                        "summary": analysis.summary,
                    })
                    if "Execution Plan" not in run.completed_stages:
                        run.completed_stages.append("Execution Plan")
                    run.execution_count += 1
                    self.save_db()
                    await asyncio.sleep(0.5)
                    continue
                except Exception as e:
                    self._handle_failure(run, project_id, "Planner Agent", "Execution Plan", e)
                    return

            # 4. REVIEWER STAGE & EVALUATION
            if not self.review_store.get(project_id):
                reqs = self.requirements_store.get(project_id)
                arch = self.architecture_store.get(project_id)
                plan = self.plan_store.get(project_id)
                if not reqs or not arch:
                    self._handle_failure(run, project_id, "Reviewer Agent", "Review", RuntimeError("Requirements or Architecture missing"))
                    return

                action_label = "Re-reviewing System" if run.correction_count > 0 else "Running Reviewer Agent"
                run.current_stage = "Review"
                run.current_agent = "Reviewer Agent"
                run.current_action = action_label
                self.save_db()

                self.activity_store.setdefault(project_id, []).insert(0, {
                    "agent": "Orchestrator",
                    "action": "Selected Reviewer Agent",
                    "provider": "System Decision",
                    "model": "Control Engine",
                    "status": "completed",
                    "duration_ms": 5,
                    "summary": f"Autonomous progression to Review (Iteration {run.review_iteration})",
                })

                try:
                    mem_ctx = self._retrieve_and_apply_memory(project, "Reviewer Agent", run)
                    analysis, duration_ms = self.reviewer_agent.analyze(project, reqs, arch, plan=plan, memory_context=mem_ctx)
                    resp = ReviewResponse(
                        **analysis.model_dump(),
                        project_id=project_id,
                        provider="Nebius Token Factory",
                        model=self.reviewer_agent.model,
                        duration_ms=duration_ms,
                    )
                    self.review_store[project_id] = resp
                    self.activity_store.setdefault(project_id, []).insert(0, {
                        "agent": "Reviewer Agent",
                        "action": "Run Project Review",
                        "provider": "Nebius Token Factory",
                        "model": self.reviewer_agent.model,
                        "status": "completed",
                        "duration_ms": duration_ms,
                        "summary": f"Identified {len(analysis.risks)} engineering risks/gaps",
                    })
                    if "Review" not in run.completed_stages:
                        run.completed_stages.append("Review")
                    run.execution_count += 1
                    self.save_db()

                    # EVALUATE REVIEW FINDINGS
                    decision, target, blocking_findings, human_prompt = self.evaluate_review(project, resp, arch, plan)
                    run.review_decision = decision
                    run.unresolved_findings = blocking_findings

                    if decision == "PASS":
                        run.unresolved_findings = []
                        if run.correction_count > 0 and getattr(run, "_last_corrected_findings", None):
                            try:
                                self._store_self_correction_lesson(
                                    project,
                                    run.correction_target,
                                    run._last_corrected_findings,
                                    f"Autonomous self-correction succeeded after {run.correction_count} cycles",
                                )
                            except Exception as e:
                                logger.warning(f"Failed to store self-correction lesson: {e}")

                        self.activity_store.setdefault(project_id, []).insert(0, {
                            "agent": "Orchestrator",
                            "action": "Review Evaluation: PASS",
                            "provider": "System Decision",
                            "model": "Control Engine",
                            "status": "completed",
                            "duration_ms": 5,
                            "summary": f"Review passed with no blocking issues (Self-corrections: {run.correction_count}). Proceeding to Testing.",
                        })
                        self.save_db()
                        await asyncio.sleep(0.5)
                        continue

                    elif decision == "HUMAN_DECISION_REQUIRED":
                        run.state = OrchestratorState.PAUSED
                        run.is_running = False
                        run.human_input_required = True
                        run.human_decision_prompt = HumanDecisionPrompt(**(human_prompt or {}))
                        run.last_error = f"Human decision required: {(human_prompt or {}).get('question', '')}"
                        run.error_message = run.last_error
                        run.failed_stage = "Requirements"
                        self.activity_store.setdefault(project_id, []).insert(0, {
                            "agent": "Orchestrator",
                            "action": "Review Evaluation: HUMAN_DECISION_REQUIRED",
                            "provider": "System Decision",
                            "model": "Control Engine",
                            "status": "completed",
                            "duration_ms": 5,
                            "summary": f"Human decision required: {(human_prompt or {}).get('question', '')}",
                        })
                        self.save_db()
                        return

                    elif decision == "CORRECTION_REQUIRED":
                        if run.correction_count >= run.max_corrections:
                            run.state = OrchestratorState.PAUSED
                            run.is_running = False
                            run.last_error = f"Reviewer feedback remains unresolved after maximum self-correction attempts ({run.max_corrections})."
                            run.error_message = run.last_error
                            run.failed_stage = target
                            self.activity_store.setdefault(project_id, []).insert(0, {
                                "agent": "Orchestrator",
                                "action": "Self-Correction Paused (Max Limit Reached)",
                                "provider": "System Decision",
                                "model": "Control Engine",
                                "status": "completed",
                                "duration_ms": 5,
                                "summary": f"Max correction cycles ({run.max_corrections}) reached with unresolved findings.",
                            })
                            self.save_db()
                            return

                        run.correction_count += 1
                        run.correction_cycles = run.correction_count
                        run.review_iteration += 1
                        run.correction_target = target
                        run._last_corrected_findings = blocking_findings

                        top_finding = blocking_findings[0]
                        self.activity_store.setdefault(project_id, []).insert(0, {
                            "agent": "Orchestrator",
                            "action": "Autonomous Decision: CORRECTION_REQUIRED",
                            "provider": "System Decision",
                            "model": "Control Engine",
                            "status": "completed",
                            "duration_ms": 5,
                            "summary": f"Correction cycle {run.correction_count}/{run.max_corrections}: Correcting {target}. Reason: {top_finding.get('title')}",
                        })

                        if target == "Architecture Agent":
                            self.invalidate_downstream(project_id, "Architecture Agent", f"Review risk: {top_finding.get('title')}")
                            existing_arch = self.architecture_store.pop(project_id, None)
                            if "Architecture" in run.completed_stages:
                                run.completed_stages.remove("Architecture")

                            run.current_stage = "Architecture"
                            run.current_agent = "Architecture Agent"
                            run.current_action = f"Correcting Architecture (Cycle {run.correction_count})"
                            self.save_db()

                            mem_ctx = self._retrieve_and_apply_memory(project, "Architecture Agent", run)
                            corr_analysis, corr_duration = self.architecture_agent.analyze(
                                project, reqs, existing_architecture=existing_arch, reviewer_findings=blocking_findings, memory_context=mem_ctx
                            )
                            arch_resp = ArchitectureResponse(
                                **corr_analysis.model_dump(),
                                project_id=project_id,
                                provider="Nebius Token Factory",
                                model=self.architecture_agent.model,
                                duration_ms=corr_duration,
                            )
                            self.architecture_store[project_id] = arch_resp
                            self.activity_store.setdefault(project_id, []).insert(0, {
                                "agent": "Architecture Agent",
                                "action": f"Correct Architecture (Cycle {run.correction_count})",
                                "provider": "Nebius Token Factory",
                                "model": self.architecture_agent.model,
                                "status": "completed",
                                "duration_ms": corr_duration,
                                "summary": f"Revised architecture resolving reviewer findings: {corr_analysis.summary}",
                            })
                            run.completed_stages.append("Architecture")
                            run.execution_count += 1
                            self.save_db()
                            await asyncio.sleep(0.5)
                            continue

                        elif target == "Planner Agent":
                            self.invalidate_downstream(project_id, "Planner Agent", f"Review risk: {top_finding.get('title')}")
                            existing_plan = self.plan_store.pop(project_id, None)
                            if "Execution Plan" in run.completed_stages:
                                run.completed_stages.remove("Execution Plan")

                            run.current_stage = "Execution Plan"
                            run.current_agent = "Planner Agent"
                            run.current_action = f"Correcting Execution Plan (Cycle {run.correction_count})"
                            self.save_db()

                            mem_ctx = self._retrieve_and_apply_memory(project, "Planner Agent", run)
                            corr_plan_analysis, corr_plan_duration = self.planner_agent.analyze(
                                project, reqs, arch, existing_plan=existing_plan, reviewer_findings=blocking_findings, memory_context=mem_ctx
                            )
                            plan_resp = PlannerResponse(
                                **corr_plan_analysis.model_dump(),
                                project_id=project_id,
                                provider="Nebius Token Factory",
                                model=self.planner_agent.model,
                                duration_ms=corr_plan_duration,
                            )
                            self.plan_store[project_id] = plan_resp
                            self.activity_store.setdefault(project_id, []).insert(0, {
                                "agent": "Planner Agent",
                                "action": f"Correct Execution Plan (Cycle {run.correction_count})",
                                "provider": "Nebius Token Factory",
                                "model": self.planner_agent.model,
                                "status": "completed",
                                "duration_ms": corr_plan_duration,
                                "summary": f"Revised plan resolving reviewer findings: {corr_plan_analysis.summary}",
                            })
                            run.completed_stages.append("Execution Plan")
                            run.execution_count += 1
                            self.save_db()
                            await asyncio.sleep(0.5)
                            continue

                except Exception as e:
                    self._handle_failure(run, project_id, "Reviewer Agent", "Review", e)
                    return

            # 5. TEST STAGE
            if not self.test_store.get(project_id):
                reqs = self.requirements_store.get(project_id)
                arch = self.architecture_store.get(project_id)
                plan = self.plan_store.get(project_id)
                review = self.review_store.get(project_id)
                if not reqs or not arch:
                    self._handle_failure(run, project_id, "Test Agent", "Testing", RuntimeError("Requirements or Architecture missing"))
                    return

                run.current_stage = "Testing"
                run.current_agent = "Test Agent"
                run.current_action = "Running Test Agent"
                self.save_db()

                self.activity_store.setdefault(project_id, []).insert(0, {
                    "agent": "Orchestrator",
                    "action": "Selected Test Agent",
                    "provider": "System Decision",
                    "model": "Control Engine",
                    "status": "completed",
                    "duration_ms": 5,
                    "summary": "Autonomous progression to Verification & Testing",
                })

                try:
                    mem_ctx = self._retrieve_and_apply_memory(project, "Test Agent", run)
                    analysis, duration_ms = self.test_agent.analyze(project, reqs, arch, plan=plan, review=review, memory_context=mem_ctx)
                    resp = TestResponse(
                        **analysis.model_dump(),
                        project_id=project_id,
                        provider="Nebius Token Factory",
                        model=self.test_agent.model,
                        duration_ms=duration_ms,
                    )
                    self.test_store[project_id] = resp
                    self.activity_store.setdefault(project_id, []).insert(0, {
                        "agent": "Test Agent",
                        "action": "Generate Verification Strategy",
                        "provider": "Nebius Token Factory",
                        "model": self.test_agent.model,
                        "status": "completed",
                        "duration_ms": duration_ms,
                        "summary": f"{len(analysis.test_cases)} verification scenarios generated",
                    })
                    if "Testing" not in run.completed_stages:
                        run.completed_stages.append("Testing")
                    run.execution_count += 1
                    self.save_db()
                    await asyncio.sleep(0.5)
                    continue
                except Exception as e:
                    self._handle_failure(run, project_id, "Test Agent", "Testing", e)
                    return

            # 6. PIPELINE COMPLETION
            all_done = all(s[0] in run.completed_stages for s in STAGE_SEQUENCE)
            if all_done and run.state != OrchestratorState.PAUSED:
                run.state = OrchestratorState.COMPLETED
                run.is_running = False
                run.current_stage = ""
                run.current_agent = ""
                run.current_action = "PROJECT READY FOR EXECUTION"
                run.completed_at = self.now_iso()
                self.save_db()
                break

    def _handle_failure(
        self,
        run: OrchestratorRun,
        project_id: str,
        agent_name: str,
        stage_name: str,
        error: Exception,
    ) -> None:
        logger.error(f"Orchestrator stage '{stage_name}' failed: {error}", exc_info=True)
        run.state = OrchestratorState.PAUSED
        run.is_running = False
        run.failed_stage = agent_name
        run.last_error = str(error)
        run.error_message = str(error)
        run.current_action = f"Paused due to {agent_name} error"

        self.activity_store.setdefault(project_id, []).insert(0, {
            "agent": agent_name,
            "action": f"Autonomous {stage_name}",
            "provider": "Nebius Token Factory",
            "model": "nvidia/Nemotron-3-Ultra-550b-a55b",
            "status": "failed",
            "duration_ms": 0,
            "summary": str(error),
        })
        self.save_db()
